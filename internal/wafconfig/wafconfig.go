// Package wafconfig mirrors the operator's WAF overrides from /etc/cfm into
// the edge's Lua directory.
//
// The operator edits /etc/cfm/cfm_waf_config.lua (`return { rule_<name> =
// "<mode>", … }`). The edge cannot read it: /etc/cfm is root-only (0700) and
// the nginx / angie workers run as the `cfm` user. So, like every other
// operator-derived Lua file (cfm_ignore_nets.lua, cfm_self_ips.lua,
// cfm_sslcollector_config.lua), the daemon copies it into /var/lib/cfm/lua/
// as root:cfm 0640, where cfm_waf.lua `require`s it. The copy starts with
// Header; a file there without it was placed by hand and is backed up before
// the first overwrite.
//
// Before this package, the docs and release notes told operators to write the
// file in /etc/cfm, and nothing ever read it there (found 2026-11-18; no node
// had one, so no override was silently lost).
package wafconfig

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"os/user"
	"path/filepath"
	"strconv"
	"sync"
	"time"
)

// Header starts every file this package writes. Its presence marks the Lua
// copy as ours (safe to replace or remove); keep it a Lua comment.
const Header = "-- generated by cfm from /etc/cfm/cfm_waf_config.lua: edit that file, not this one\n"

// maxSize bounds the operator file. A real override is a few hundred bytes.
const maxSize = 256 << 10

// SourcePath and LuaPath are vars so tests can point them at a temp dir.
var (
	SourcePath = "/etc/cfm/cfm_waf_config.lua"
	LuaPath    = "/var/lib/cfm/lua/cfm_waf_config.lua"
)

var mu sync.Mutex

// Result says what one Sync did.
type Result int

const (
	Unchanged Result = iota // nothing to do
	Written                 // the Lua copy was (re)written
	Removed                 // the source is gone; our copy was removed
)

// Sync makes LuaPath follow SourcePath. It compares contents on every call
// (the file is a few hundred bytes), so a copy edited by hand, or a source
// saved twice within one timestamp tick, is put right on the next poll. The
// edge loads the copy once per worker: a change takes effect at the next
// edge reload.
func Sync() (Result, error) {
	mu.Lock()
	defer mu.Unlock()

	st, err := os.Stat(SourcePath)
	if err != nil {
		if !os.IsNotExist(err) {
			return Unchanged, fmt.Errorf("waf config: stat %s: %w", SourcePath, err)
		}
		// Source absent: remove our copy, never a hand-placed file.
		ours, exists, err := isOurs(LuaPath)
		if err != nil {
			return Unchanged, err
		}
		if exists && ours {
			if err := os.Remove(LuaPath); err != nil && !os.IsNotExist(err) {
				return Unchanged, fmt.Errorf("waf config: remove %s: %w", LuaPath, err)
			}
			return Removed, nil
		}
		return Unchanged, nil
	}
	if !st.Mode().IsRegular() {
		return Unchanged, fmt.Errorf("waf config: %s is not a regular file (the copy the edge loads, if any, is left as it was)", SourcePath)
	}
	if st.Size() > maxSize {
		return Unchanged, fmt.Errorf("waf config: %s is %d bytes, over the %d-byte limit (the copy the edge loads, if any, is left as it was)", SourcePath, st.Size(), maxSize)
	}
	src, err := os.ReadFile(SourcePath)
	if err != nil {
		return Unchanged, fmt.Errorf("waf config: read %s: %w", SourcePath, err)
	}
	want := append([]byte(Header), src...)

	ours, exists, err := isOurs(LuaPath)
	if err != nil {
		return Unchanged, err
	}
	if exists && ours {
		if cur, err := os.ReadFile(LuaPath); err == nil && bytes.Equal(cur, want) {
			return Unchanged, nil
		}
	}
	if exists && !ours {
		// A hand-placed override (the only way that worked before): keep a
		// copy rather than overwrite it silently.
		bak := LuaPath + ".handplaced." + time.Now().UTC().Format("20060102T150405Z")
		if err := os.Rename(LuaPath, bak); err != nil {
			return Unchanged, fmt.Errorf("waf config: back up hand-placed %s: %w", LuaPath, err)
		}
	}
	if err := writeGroupReadable(LuaPath, want); err != nil {
		return Unchanged, err
	}
	return Written, nil
}

// isOurs reports whether path exists and starts with Header.
func isOurs(path string) (ours, exists bool, err error) {
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return false, false, nil
		}
		return false, false, fmt.Errorf("waf config: open %s: %w", path, err)
	}
	defer f.Close()
	buf := make([]byte, len(Header))
	n, err := io.ReadFull(f, buf)
	if err != nil && err != io.ErrUnexpectedEOF && err != io.EOF {
		return false, true, fmt.Errorf("waf config: read %s: %w", path, err)
	}
	return string(buf[:n]) == Header, true, nil
}

// writeGroupReadable writes data atomically as root:cfm 0640, the mode the
// edge worker (group cfm) needs. The explicit chmod matters: os.WriteFile's
// mode is umask-filtered, and a hardened 0077 umask would leave the file 0600,
// unreadable to the worker (the IGNORE_NETS cache once died that way).
func writeGroupReadable(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("waf config: mkdir %s: %w", dir, err)
	}
	// The worker must traverse the dir too: if the daemon created it just now
	// it is root:root, and LuaJIT reads an unreachable file as "module not
	// found", i.e. silently no overrides. Same as detectors/ignore.go.
	chownCFMGroup(dir)
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o640); err != nil {
		return fmt.Errorf("waf config: write %s: %w", tmp, err)
	}
	if err := os.Chmod(tmp, 0o640); err != nil { // #nosec G302 -- group read is required: the cfm-group edge worker loads this file.
		_ = os.Remove(tmp)
		return fmt.Errorf("waf config: chmod %s: %w", tmp, err)
	}
	chownCFMGroup(tmp)
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("waf config: rename to %s: %w", path, err)
	}
	return nil
}

// chownCFMGroup gives path to the cfm group (uid unchanged); a no-op where the
// group does not exist (tests, dev boxes).
func chownCFMGroup(path string) {
	g, err := user.LookupGroup("cfm")
	if err != nil || g == nil {
		return
	}
	gid, err := strconv.Atoi(g.Gid)
	if err != nil {
		return
	}
	_ = os.Chown(path, -1, gid)
}
